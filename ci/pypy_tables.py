"""Builds the PyPy tables rpyenv embeds (M7a design §4.1, §5.1).

  python3 ci/pypy_tables.py --share <python-build share dir> --pages <dir> [--engine docker|podman|local] [--write] [--write-lists]

--share is the vendored crates/pyenv/python-build/share; --pages holds pypy.org's
versions.json and checksums.html, fetched by the caller. The upstream definitions are run by
crates/pyenv/src/install/pypy_eval.sh with stub python-build functions, in a container with no
network and a read-only file system (`local` runs bash directly: tests only). Any failure exits
1 before anything is written. Without --write it reports whether the tables would change.
"""
import argparse
import json
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(REPO, "crates", "pyenv", "pypy")
EVAL = os.path.join(REPO, "crates", "pyenv", "src", "install", "pypy_eval.sh")
ARCHES = ("linux64", "linux-aarch64")
# debian:trixie-slim as pulled on 2026-10-14, pinned by digest so the table is reproducible
# (`docker image inspect --format '{{index .RepoDigests 0}}' debian:trixie-slim` after a pull).
IMAGE = "debian:trixie-slim@sha256:a29215f6a35e51e22adffa17f89e9d2ef06214e64a2bad10d765c46aea49f11f"
LOOP = 'for n in "$@"; do for a in linux64 linux-aarch64; do printf "%s\\t%s\\t" "$n" "$a"; bash "$EVAL" "$DEFS/$n" "$a"; done; done'


def pypy_names(share):
    """Every `pypy*` definition file in `share`, sorted (C order)."""
    return sorted(n for n in os.listdir(share) if n.startswith("pypy") and os.path.isfile(os.path.join(share, n)))


def evaluate(share, names, engine):
    """{(name, arch): verdict line} for each binary definition in `names` and each of ARCHES."""
    if not names:
        return {}
    if engine == "local":
        cmd = ["bash", "-c", LOOP, "_", *names]
        env = dict(os.environ, EVAL=EVAL, DEFS=share)
    else:
        cmd = [engine, "run", "--rm", "--network", "none", "--read-only",
               "-v", f"{os.path.abspath(share)}:/defs:ro", "-v", f"{EVAL}:/eval.sh:ro",
               "-e", "EVAL=/eval.sh", "-e", "DEFS=/defs", IMAGE, "bash", "-c", LOOP, "_", *names]
        env = None
    out = subprocess.run(cmd, capture_output=True, text=True, check=True, env=env).stdout
    verdicts = {}
    for line in out.splitlines():
        name, arch, verdict = line.split("\t", 2)
        verdicts[(name, arch)] = verdict
    want = {(n, a) for n in names for a in ARCHES}
    if set(verdicts) != want:
        raise RuntimeError(f"the evaluator answered for {len(verdicts)} of {len(want)} definition/arch pairs")
    return verdicts


THIRD_PARTY = "unsupported third-party build"


def linux_rows(names, verdicts):
    """[(name, arch, verdict)] for every name: `-src` ones are `unsupported source build`, and an
    `ok` verdict whose URL is not under PyPy's folder is `unsupported third-party build` (ruling R7)."""
    rows = []
    for n in names:
        for a in ARCHES:
            v = "unsupported source build" if n.endswith("-src") else verdicts[(n, a)]
            if v.startswith("ok ") and not v.split()[2].startswith(DOWNLOADS):
                v = THIRD_PARTY
            rows.append((n, a, v))
    return rows


def render_linux(rows):
    head = ("# Generated by ci/pypy_tables.py from upstream's PyPy definitions (M7a design §4.1).\n"
            "# <name>\\t<arch>\\t<verdict of crates/pyenv/src/install/pypy_eval.sh>\n")
    return head + "".join(f"{n}\t{a}\t{v}\n" for n, a, v in rows)


DOWNLOADS = "https://downloads.python.org/pypy/"
# Fewer pairs than this means the page's layout changed (1021 on 2026-10-14). Same number as
# install::pypy::MIN_PAGE_HASHES.
MIN_PAGE_HASHES = 500
# Fewer rows than this means versions.json changed shape (60 on 2026-10-14).
MIN_WINDOWS_ROWS = 50
HASH = re.compile(r"[0-9a-f]{64}")
FILE = re.compile(r"pypy[A-Za-z0-9_.\-]*\.(?:zip|tar\.bz2|tar\.gz)")
# pyenv-win's own pattern for PyPy zips (pyenv-install-lib.vbs regexJsonUrl), win64 only.
WIN = re.compile(r"^(pypy(\d+)\.(\d+)-v(\d+(?:\.\d+){0,2})-win64)\.zip$")


def page_hashes(html):
    """{file: sha256} from pypy.org's checksum page: tags removed, then each `<64 hex> <pypy
    file>` pair of words. install::pypy::page_hashes does the same."""
    words = re.sub(r"<[^>]*>", " ", html).split()
    out = {}
    for a, b in zip(words, words[1:]):
        if HASH.fullmatch(a) and FILE.fullmatch(b) and out.setdefault(b, a) != a:
            raise ValueError(f"pypy.org's checksum page gives two SHA-256 values for {b}")
    if len(out) < MIN_PAGE_HASHES:
        raise ValueError(f"pypy.org's checksum page has {len(out)} SHA-256 lines, fewer than {MIN_PAGE_HASHES}: has its layout changed?")
    return out


def windows_rows(versions_json, sums, minimum=MIN_WINDOWS_ROWS):
    """[(code, url, sha256)] for the zips pyenv-win lists that have a published hash, in
    pyenv-win's order: Python version, then PyPy version."""
    rows = {}
    for rel in json.loads(versions_json):
        for f in rel.get("files", []):
            m = WIN.match(f.get("filename", ""))
            if not m:
                continue
            url = f["download_url"]
            if url != DOWNLOADS + f["filename"]:
                raise ValueError(f"{f['filename']}: download_url {url} is not under {DOWNLOADS}")
            if f["filename"] in sums:
                rows[m.group(1)] = (url, sums[f["filename"]])

    def key(code):
        m = WIN.match(code + ".zip")
        return (int(m.group(2)), int(m.group(3)), tuple(int(x) for x in m.group(4).split(".")))
    if len(rows) < minimum:
        raise ValueError(f"versions.json gave {len(rows)} Windows PyPy zips with published hashes, fewer than {minimum}: has its layout changed?")
    return [(c, *rows[c]) for c in sorted(rows, key=key)]


def render_windows(rows):
    head = ("# Generated by ci/pypy_tables.py from pypy.org's versions.json and checksums.html (M7a design §5.1).\n"
            "# <pyenv-win code>\\t<url>\\t<sha256>\n")
    return head + "".join(f"{c}\t{u}\t{h}\n" for c, u, h in rows)


def check_linux(rows, sums, unpublished, unsupported):
    """Error lines: an `ok` row whose file pypy.org lists with another hash, or doesn't list and
    linux-unpublished.txt doesn't name; an unexpected `unsupported` row; a stale list entry."""
    errors, seen_files, seen_names = [], set(), set()
    for name, arch, verdict in rows:
        w = verdict.split()
        if w[0] == "ok":
            base, _, sha = w[2].partition("#")
            file = base.rsplit("/", 1)[1]
            seen_files.add(file)
            if (arch == "linux-aarch64") != ("aarch64" in file):
                errors.append(f"{name} {arch}: " + (f"linux64 row names an aarch64 file ({file})" if arch == "linux64"
                                                    else f"linux-aarch64 row names a file without aarch64 ({file})"))
            if file in sums and sums[file] != sha:
                errors.append(f"{name} {arch}: upstream's SHA-256 for {file} differs from pypy.org's")
            elif file not in sums and file not in unpublished:
                errors.append(f"{name} {arch}: {file} is not on pypy.org's checksum page and not in linux-unpublished.txt")
        elif w[0] == "unsupported" and not name.endswith("-src") and verdict != THIRD_PARTY:
            seen_names.add(name)
            if name not in unsupported:
                errors.append(f"{name} {arch}: {verdict} (add a stub, or list it in linux-unsupported.txt)")
    errors += [f"linux-unpublished.txt: {f} is no longer in any definition" for f in sorted(unpublished - seen_files)]
    errors += [f"linux-unsupported.txt: {n} is no longer unsupported" for n in sorted(unsupported - seen_names)]
    return errors


def read_list(name):
    p = os.path.join(DEST, name)
    if not os.path.exists(p):
        return set()
    with open(p, encoding="utf-8") as f:
        return {l.strip() for l in f if l.strip() and not l.startswith("#")}


def main(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--share", required=True)
    p.add_argument("--pages", required=True)
    p.add_argument("--engine", default="docker", choices=["docker", "podman", "local"])
    p.add_argument("--write", action="store_true")
    p.add_argument("--write-lists", action="store_true",
                   help="first run only: write linux-unpublished.txt and linux-unsupported.txt from what it finds")
    a = p.parse_args(argv)
    with open(os.path.join(a.pages, "checksums.html"), encoding="utf-8") as f:
        sums = page_hashes(f.read())
    with open(os.path.join(a.pages, "versions.json"), encoding="utf-8") as f:
        win = windows_rows(f.read(), sums)
    names = pypy_names(a.share)
    rows = linux_rows(names, evaluate(a.share, [n for n in names if not n.endswith("-src")], a.engine))
    if a.write_lists:
        unpublished = {v.split()[2].partition("#")[0].rsplit("/", 1)[1] for _, _, v in rows if v.startswith("ok ")} - set(sums)
        unsupported = {n for n, _, v in rows if v.startswith("unsupported") and not n.endswith("-src") and v != THIRD_PARTY}
        os.makedirs(DEST, exist_ok=True)
        for fname, items, what in (("linux-unpublished.txt", unpublished, "files pypy.org's checksum page doesn't list"),
                                   ("linux-unsupported.txt", unsupported, "binary definitions the stubs can't evaluate")):
            with open(os.path.join(DEST, fname), "w", encoding="utf-8", newline="\n") as f:
                f.write(f"# Upstream PyPy {what} (M7a design §4.1); reviewed by hand.\n")
                f.write("".join(f"{i}\n" for i in sorted(items)))
    errors = check_linux(rows, sums, read_list("linux-unpublished.txt"), read_list("linux-unsupported.txt"))
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        return 1
    tables = {"linux.tsv": render_linux(rows), "windows.tsv": render_windows(win)}
    changed = []
    for fname, text in tables.items():
        path = os.path.join(DEST, fname)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            changed.append(fname)
            if a.write:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    print(f"linux.tsv: {len(rows)} rows; windows.tsv: {len(win)} rows; changed: {', '.join(changed) or 'none'}")
    return 0 if a.write or not changed else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
