"""Builds the PyPy tables rpyenv embeds (M7a design §4.1, §5.1).

  python3 ci/pypy_tables.py --share <python-build share dir> --pages <dir> [--engine docker|podman|local] [--write] [--write-lists]

--share is the vendored crates/pyenv/python-build/share; --pages holds pypy.org's
versions.json and checksums.html, fetched by the caller. The upstream definitions are run by
crates/pyenv/src/install/pypy_eval.sh with stub python-build functions, in a container with no
network and a read-only file system (`local` runs bash directly: tests only). Any failure exits
1 before anything is written. Without --write it reports whether the tables would change.
"""
import argparse
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(REPO, "crates", "pyenv", "pypy")
EVAL = os.path.join(REPO, "crates", "pyenv", "src", "install", "pypy_eval.sh")
ARCHES = ("linux64", "linux-aarch64")
IMAGE = "debian:trixie-slim"
LOOP = 'for n in "$@"; do for a in linux64 linux-aarch64; do printf "%s\\t%s\\t" "$n" "$a"; bash "$EVAL" "$DEFS/$n" "$a"; done; done'


def pypy_names(share):
    """Every `pypy*` definition file in `share`, sorted (C order)."""
    return sorted(n for n in os.listdir(share) if n.startswith("pypy") and os.path.isfile(os.path.join(share, n)))


def evaluate(share, names, engine):
    """{(name, arch): verdict line} for each binary definition in `names` and each of ARCHES."""
    if not names:
        return {}
    if engine == "local":
        cmd = ["bash", "-c", LOOP, "_", *names]
        env = dict(os.environ, EVAL=EVAL, DEFS=share)
    else:
        cmd = [engine, "run", "--rm", "--network", "none", "--read-only",
               "-v", f"{os.path.abspath(share)}:/defs:ro", "-v", f"{EVAL}:/eval.sh:ro",
               "-e", "EVAL=/eval.sh", "-e", "DEFS=/defs", IMAGE, "bash", "-c", LOOP, "_", *names]
        env = None
    out = subprocess.run(cmd, capture_output=True, text=True, check=True, env=env).stdout
    verdicts = {}
    for line in out.splitlines():
        name, arch, verdict = line.split("\t", 2)
        verdicts[(name, arch)] = verdict
    want = {(n, a) for n in names for a in ARCHES}
    if set(verdicts) != want:
        raise RuntimeError(f"the evaluator answered for {len(verdicts)} of {len(want)} definition/arch pairs")
    return verdicts


def linux_rows(names, verdicts):
    """[(name, arch, verdict)] for every name: `-src` ones are `unsupported source build`."""
    rows = []
    for n in names:
        for a in ARCHES:
            rows.append((n, a, "unsupported source build" if n.endswith("-src") else verdicts[(n, a)]))
    return rows


def render_linux(rows):
    head = ("# Generated by ci/pypy_tables.py from upstream's PyPy definitions (M7a design §4.1).\n"
            "# <name>\\t<arch>\\t<verdict of crates/pyenv/src/install/pypy_eval.sh>\n")
    return head + "".join(f"{n}\t{a}\t{v}\n" for n, a, v in rows)
